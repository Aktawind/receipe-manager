  /// Mot (ou expression) → rayon, avec les mots au singulier.
  static final Map<String, String> _index = {
    for (final MapEntry(key: aisle, value: words) in _byAisle.entries)
      for (final word in words)
        ShoppingProducts.keyOf(word): DefaultAisles.idFor(aisle),
  };

  static final int _longest = _index.keys.fold(
    1,
    (longest, key) =>
        key.split(' ').length > longest ? key.split(' ').length : longest,
  );

  /// Le rayon de [name] d'après le dictionnaire : l'expression la plus
  /// longue au début du nom d'abord (« pomme de terre nouvelle »), puis le
  /// premier mot connu (« filet de saumon » → Poissonnerie ; « jus
  /// d'orange » → Boissons). `null` si rien n'est connu.
  static String? fromDictionary(String name) {
    final words = ShoppingProducts.keyOf(name).split(' ');
    for (var start = 0; start < words.length; start++) {
      for (var length = _longest; length >= 1; length--) {
        if (start + length > words.length) continue;
        final phrase = words.sublist(start, start + length).join(' ');
        final aisle = _index[phrase];
        if (aisle != null) return aisle;
      }
    }
    return null;
  }

  /// Le rayon où ranger [item] : son rayon choisi, celui retenu pour ce
  /// produit, ou celui du dictionnaire — s'il existe encore dans [aisles].
  /// `null` = « Autres ».
  static String? of(
    ShoppingItem item, {
    required Map<String, String> memory,
    required Set<String> aisles,
  }) {
    for (final candidate in [
      item.aisleId,
      memory[ShoppingProducts.keyOf(item.name)],
      fromDictionary(item.name),
    ]) {
      if (candidate != null && aisles.contains(candidate)) return candidate;
    }
    return null;
  }
}
